const fs=require('fs');
const DIACSRC='[\\u064B-\\u0652\\u0670\\u0640\\u0653-\\u0655]';
const DIAC=new RegExp(DIACSRC);
const CLS={
 'ي':'[يیى]','ی':'[يیى]','ى':'[يیى]',
 'ك':'[كک]','ک':'[كک]',
 'ا':'[اأإآٱ]','أ':'[اأإآٱ]','إ':'[اأإآٱ]','آ':'[اأإآٱ]','ٱ':'[اأإآٱ]',
 'ة':'[ةه]','ه':'[ةه]',
 'و':'[وؤ]','ؤ':'[وؤ]'
};
function pat(needle){
  let out='';
  for(const ch of needle){
    if(DIAC.test(ch)) continue;
    const base = CLS[ch] || ch.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
    out += base + DIACSRC + '*';
  }
  return out;
}
function grab(file,a,b,line){
  const lines=fs.readFileSync(file,'utf8').split('\n');
  const re=b? new RegExp(pat(a)+'[\\s\\S]*?'+pat(b)) : new RegExp(pat(a));
  let m = lines[line-1] && lines[line-1].match(re);
  if(!m){
    for(let i=0;i<lines.length;i++){
      const mm=lines[i].match(re);
      if(mm){ m=mm; console.error('  [hint line '+line+' missed; used line '+(i+1)+' of '+file+']'); break; }
    }
  }
  if(!m) throw new Error('NOT FOUND '+file+' ('+a+' .. '+b+')');
  if(m[0].includes('\n')) throw new Error('span newline');
  return m[0];
}
const items=[];
function add(file,line,a,b,fa,src,d){
  const ar=grab(file,a,b,line);
  const words=ar.split(' ');
  if(words.join(' ')!==ar) throw new Error('split mismatch: '+ar);
  items.push({ar,fa,src,words,d,_src:file+':'+line});
}
